LANGUAGES = {"en": _EN, "de": _DE}


class Lang:
    """Labels and number formatting for one language (``"en"`` or ``"de"``)."""

    def __init__(self, code: str = "en") -> None:
        if code not in LANGUAGES:
            raise ValueError(f"Unknown report language {code!r}; use one of {sorted(LANGUAGES)}.")
        self.code = code
        self.texts = LANGUAGES[code]

    def __call__(self, key: str, **values: Any) -> str:
        """Text for ``key``, with ``values`` filled into its placeholders."""
        text = self.texts[key]
        return text.format(**values) if values else text

    def num(self, value: Any, digits: int = 2) -> str:
        """Format a number with the thousands and decimal marks of the language."""
        if value is None:
            return "–"
        if isinstance(value, float):
            text = f"{value:,.{digits}f}"
        elif isinstance(value, int):
            text = f"{value:,}"
        else:
            return str(value)
        return text.translate(str.maketrans(",.", ".,")) if self.code == "de" else text

    def pct(self, part: float, whole: float) -> str:
        """Format ``part / whole`` as a percentage, or a dash when ``whole`` is zero."""
        return f"{self.num(100 * part / whole, 1)} %" if whole else "–"

    def warning(self, code: str, message: str) -> str:
        """Translated text of a recorded warning, falling back to its stored message."""
        return self.texts.get(f"w_{code}", message)
